#!/usr/bin/env bash
# Starts the Kesher chat display full-screen on the local monitor.
# Run by kesher-chat-kiosk.service (cage as Wayland kiosk compositor on tty1).
# With KIOSK_URL set (e.g. the multiview output, which embeds the chat as a
# tile), that page is shown instead of the plain chat view.
# KIOSK_URL="screens": every connected monitor (HDMI, DisplayPort, VGA ...)
# shows the multiview chosen for it in the multiview editor. That needs sway
# instead of cage, because cage can only drive a single monitor.
set -euo pipefail

CONFIG_FILE="/etc/kesher/chat-kiosk.env"
if [[ -f "${CONFIG_FILE}" ]]; then
  # shellcheck disable=SC1090
  source "${CONFIG_FILE}"
fi

KESHER_URL="${KESHER_URL:-http://127.0.0.1:8080}"
KESHER_USERNAME="${KESHER_USERNAME:-Chat-Monitor}"
KESHER_ROLE_ID="${KESHER_ROLE_ID:-chat-monitor}"
KIOSK_URL="${KIOSK_URL:-}"
KIOSK_HEALTH_URL="${KIOSK_HEALTH_URL:-}"
MULTIVIEW_URL="${MULTIVIEW_URL:-http://127.0.0.1:8090}"
HEALTH_TIMEOUT_SECONDS="${HEALTH_TIMEOUT_SECONDS:-300}"

urlencode() {
  local raw="$1" out="" ch i
  for ((i = 0; i < ${#raw}; i++)); do
    ch="${raw:i:1}"
    case "${ch}" in
      [a-zA-Z0-9.~_-]) out+="${ch}" ;;
      *) out+="$(printf '%%%02X' "'${ch}")" ;;
    esac
  done
  printf '%s' "${out}"
}

if [[ "${KIOSK_URL}" == "screens" ]]; then
  HEALTH_URL="${KIOSK_HEALTH_URL:-${MULTIVIEW_URL%/}/api/state}"
elif [[ -n "${KIOSK_URL}" ]]; then
  HEALTH_URL="${KIOSK_HEALTH_URL:-${KIOSK_URL}}"
else
  HEALTH_URL="${KESHER_URL}/api/healthz"
fi

# Wait for the page instead of showing a browser error page after boot.
deadline=$((SECONDS + HEALTH_TIMEOUT_SECONDS))
until curl -fsS --max-time 3 "${HEALTH_URL}" >/dev/null 2>&1; do
  if ((SECONDS >= deadline)); then
    echo "Not reachable: ${HEALTH_URL} after ${HEALTH_TIMEOUT_SECONDS}s" >&2
    exit 1
  fi
  sleep 3
done

BROWSER=""
for candidate in /snap/bin/chromium /usr/bin/chromium /usr/bin/chromium-browser; do
  if [[ -x "${candidate}" ]]; then
    BROWSER="${candidate}"
    break
  fi
done
if [[ -z "${BROWSER}" ]]; then
  echo "Chromium not found." >&2
  exit 1
fi

BROWSER_FLAGS=(
  --ozone-platform=wayland
  --no-first-run
  --no-default-browser-check
  --noerrdialogs
  --disable-infobars
  --disable-session-crashed-bubble
  --lang=de
  --disable-translate
  --disable-features=Translate,TranslateUI,MediaRouter
  --disable-sync
  --disable-extensions
  --password-store=basic
  --check-for-update-interval=31536000
  --overscroll-history-navigation=0
  --autoplay-policy=no-user-gesture-required
  --use-fake-ui-for-media-stream
  --mute-audio
)

if [[ "${KIOSK_URL}" == "screens" ]]; then
  # sway puts each window on its monitor by title ("Bildschirm HDMI-A-1 · Multiview"),
  # the trailing space keeps HDMI-A-1 apart from HDMI-A-10.
  SWAY_CONFIG="${XDG_RUNTIME_DIR:-/tmp}/kesher-kiosk-sway.conf"
  {
    echo "# Generated by kesher-chat-kiosk-launch.sh on every start."
    echo "xwayland disable"
    echo "default_border none"
    echo "default_floating_border none"
    echo "focus_follows_mouse no"
    echo "seat * hide_cursor 3000"
    for status in /sys/class/drm/card*-*/status; do
      name="${status%/status}"
      name="${name##*/}"
      name="${name#card*-}"
      [[ "${name}" == Writeback* ]] && continue
      echo "for_window [title=\"^Bildschirm ${name} \"] move container to output ${name}, fullscreen enable"
    done
    echo "exec $(dirname "$(readlink -f "$0")")/kesher-screens-session.sh"
  } >"${SWAY_CONFIG}"
  export KIOSK_BROWSER="${BROWSER}" KIOSK_BROWSER_FLAGS="${BROWSER_FLAGS[*]}" MULTIVIEW_URL
  exec /usr/bin/sway --config "${SWAY_CONFIG}"
fi

DISPLAY_URL="${KIOSK_URL:-${KESHER_URL}/?autoLogin=1&autoTakeover=1&viewMode=chat&username=$(urlencode "${KESHER_USERNAME}")&roleId=$(urlencode "${KESHER_ROLE_ID}")}"

# -s keeps Ctrl+Alt+F2..F6 working for a console login on the server.
exec /usr/bin/cage -s -- "${BROWSER}" --kiosk --incognito "${BROWSER_FLAGS[@]}" "${DISPLAY_URL}"
